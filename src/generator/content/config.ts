/**
 * config.ts
 *
 * O config do workspace que o gerador grava (F3.4, passo 3): o do projeto
 * greenfield (grava o config da marca; o nome antigo `ai-sdk.config.yaml` segue legível) e o do workspace
 * brownfield (`<marca>.config.yaml`).
 *
 * Funções puras: o instante da geração e a versão do kit chegam por
 * parâmetro, e quem chama lê o relógio e o `kitVersion()`. O YAML é montado
 * por interpolação de string, exatamente como antes (o `@known-bug` do nome
 * com aspas no golden depende disso).
 */

import type { WizardState } from "../../types";
import { BRAND } from "../../data/brand.pure";

/** Config do projeto greenfield gerado pelo Wizard. */
export function buildGreenfieldConfig(state: WizardState, now: string, kitVersion: string): string {
  const templateId = `${BRAND.templatePrefix}${state.backendStack}`;
  const version = state.resolvedTemplate?.version ?? "1.0.0";

  return `# Generated by ${BRAND.displayName} on ${now}
version: "1.0.0"
kit_version: "${kitVersion}"   # versão da ${BRAND.displayName} que instalou esta estrutura
project:
  name: "${state.projectName}"
  slug: "${state.projectName}"
  
stacks:
  backend: "${state.backendStack}"${state.frontendStack !== "none" ? `\n  frontend: "${state.frontendStack}"` : ""}

architecture:
  backend: "${state.backendArchitecture}"${state.frontendArchitecture ? `\n  frontend: "${state.frontendArchitecture}"` : ""}
  
host_adapter: "${state.hostAdapter}"

delivery:
  mode: "${state.deliveryMode}"
  gates:
    g1_upstream_to_downstream:
      enabled: true
      guardians: [stream-align, arch-cross]
      trigger: sprint-planner.exit_contract
    g2_downstream_to_operation:
      enabled: true
      guardians: [stream-align, arch-cross]
      trigger: sprint-runner.merge_confirmed

templates:
  resolved:
    ${state.backendStack}:
      templateId: "${templateId}"
      version: "${version}"
      resolvedAt: "${now}"
`;
}

export interface BrownfieldConfigInput {
  projectName: string;
  /** `claude` ou `copilot`, já resolvido. */
  hostAdapter: string;
  hostDir: string;
  /** Vazio ou ausente = `["dora-4keys"]`. */
  maturityFrameworks?: readonly string[];
  now: string;
  kitVersion: string;
}

/** Config do workspace brownfield (sem stacks: o assessment as descobre). */
export function buildBrownfieldConfig(input: BrownfieldConfigInput): string {
  const fwList = (input.maturityFrameworks && input.maturityFrameworks.length > 0)
    ? input.maturityFrameworks
    : ["dora-4keys"];
  return [
    `# Generated by ${BRAND.displayName} on ${input.now}`,
    `version: "1.0.0"`,
    // Versão da extensão que instalou esta estrutura. É o que permite detectar,
    // numa atualização da extensão, que os agentes/skills do workspace ficaram
    // para trás — e oferecer a migração em vez de falhar em silêncio.
    `kit_version: "${input.kitVersion}"`,
    `project:`,
    `  name: "${input.projectName}"`,
    `  slug: "${input.projectName}"`,
    `  mode: brownfield`,
    `host_adapter: "${input.hostAdapter}"`,
    `host_dir: "${input.hostDir}"`,
    `assessment:`,
    `  status: pending`,
    `  maturity_frameworks:`,
    ...fwList.map((fw) => `    - ${fw}`),
  ].join("\n") + "\n";
}

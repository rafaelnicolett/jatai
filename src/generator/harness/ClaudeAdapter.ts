/**
 * Gera .claude/agents/, .claude/commands/ e CLAUDE.md
 * para projetos com Claude (Anthropic).
 */
export class ClaudeAdapter implements HarnessAdapter {
  readonly name = "claude";
  readonly hostDir = ".claude";
  readonly instructionsFile = "CLAUDE.md";
  readonly kitInstructionsFile = "claude-instructions.md";
  readonly supportsChatmodes = false;
  readonly slashCommandsDir = ".claude/commands";
  readonly projectHooksFile = ".claude/settings.json";

  /**
   * Adapts agent files for Claude Code host:
   * - Replaces .github/agents/ → .claude/agents/ in all .md file contents
   * - Drops a frontmatter `model:` line with Copilot model names (G8)
   * - Renames maestro.agent.md → <marca>.agent.md, como no Copilot (ADR-0025)
   */
  async adaptAgents(agentsDir: string): Promise<void> {
    // Walk all .md files and replace path prefix — só os do kit: `agents/domain/`
    // (a LLM Wiki) é do cliente e nunca é reescrito (A21, `isClientOwned`).
    const mdFiles = (await walkFilesByExt(agentsDir, ".md")).filter(
      (f) => !isClientOwned(path.posix.join("agents", path.relative(agentsDir, f).split(path.sep).join("/")))
    );
    for (const filePath of mdFiles) {
      try {
        const content = await fs.readFile(filePath, "utf-8");
        const fixed = withoutCopilotModel(content.split(".github/agents/").join(".claude/agents/"));
        if (fixed !== content) await fs.writeFile(filePath, fixed, "utf-8");
      } catch { /* skip unreadable files */ }
    }

    await renameKitOrchestrator(agentsDir);
  }

  generateAgentArtifacts(
    _targetDir: string,
    state: WizardState
  ): Promise<GeneratedFile[]> {
    const files: GeneratedFile[] = [];

    // CLAUDE.md — entry point
    files.push({
      relativePath: "CLAUDE.md",
      content: claudeMd(state),
    });

    // .claude/agents/ — stub agentes
    for (const agent of getAgentStubs(state)) {
      files.push({
        relativePath: `.claude/agents/${agent.filename}`,
        content: agent.content,
      });
    }

    // .claude/commands/helyx.md — mesmo nome do agente orquestrador (helyx.agent.md),
    // para o Claude Code registrar /helyx como ponto de entrada único.
    files.push({
      relativePath: `.claude/commands/${BRAND.files.slashCommand}`,
      content: helyxCommand(state),
    });

    return Promise.resolve(files);
  }
}

// ── Generators ─────────────────────────────────────────────────────────────

/**
 * Tira do frontmatter a linha `model:` com nomes de modelo do Copilot
 * ("Claude Sonnet 4.5 (copilot)"), que o orquestrador do kit traz para o
 * Copilot e o Claude Code não reconhece (G8, F3.5). O resto do arquivo fica
 * como está.
 */
export function withoutCopilotModel(text: string): string {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(text);
  if (!m) return text;
  const block = m[1]!;
  const kept = block.split("\n").filter((line) => !(/^model:/.test(line) && line.includes("(copilot)"))).join("\n");
  if (kept === block) return text;
  const start = text.indexOf(block);
  return text.slice(0, start) + kept + text.slice(start + block.length);
}

function claudeMd(state: WizardState): string {
  return `# ${state.projectName} — Claude Instructions

> Generated by ${BRAND.displayName} · Template \`${BRAND.templatePrefix}${state.backendStack}\`

## Ponto de entrada único

${entryPointParagraph("claude")}

## Stack
- Backend: **${state.backendStack}** · Service: \`${state.projectName.replace(/-/g, "_")}\`
${state.frontendStack !== "none" ? `- Frontend: **${state.frontendStack}**` : ""}
- Database: ${state.database ?? "postgresql"}
- Cloud: ${state.cloud ?? "none"}
- CI/CD: ${state.cicd ?? "github-actions"}

## Arquitetura
- Hexagonal / Ports & Adapters (domain → application → adapters)
- \`domain\`: zero import de framework
- \`application\`: use cases + ports
- \`adapters\`: HTTP, DB, queue

## Convenções
- Errors: \`DomainError\` → 4xx + envelope \`{ code, message, details, traceId }\`
- OTel: 1 span por entry point de adapter
- Tests: unit (domain/ — sem mocks), integration (Testcontainers)

## Fluxo

\`\`\`
UPSTREAM (descobrir & definir)  →  GATE G1
  →  DOWNSTREAM (construir & validar)  →  GATE G2
  →  OPERATION (rodar & sustentar)
\`\`\`

Gates são pontos de parada obrigatórios — o \`@${BRAND.name}\` não avança sem aprovação humana.

## Agentes e artefatos

- Agentes em \`.claude/agents/\` — um por fase do delivery
- Artefatos em \`.github/artifacts/\` — são a fonte da verdade (file-as-state)
- Agentes leem arquivos para recuperar estado; nunca recarregam histórico de chat

## Anti-padrões

- ❌ Falar direto com agentes especialistas (sempre via \`@${BRAND.name}\`)
- ❌ Pular gate (G1/G2) sem aprovação humana
- ❌ Carregar skill não declarada pela fase ativa em \`uses_skills\`
`;
}

function helyxCommand(state: WizardState): string {
  return `---
description: "Orquestrador — ponto de entrada único da ${BRAND.displayName} para ${state.projectName}"
argument-hint: "Descreva a feature/app a entregar, ou peça para continuar uma iniciativa existente"
---
# @${BRAND.name}

${orchestratorEntryBody("claude", state.projectName)}`;
}

interface AgentStub {
  filename: string;
  content: string;
}

function getAgentStubs(state: WizardState): AgentStub[] {
  return [
    {
      filename: `backend-${state.backendStack}.agent.md`,
      content: `---
id: backend-${state.backendStack}
stream: downstream
---
# @backend-${state.backendStack}

Stack: **${state.backendStack}** · Project: ${state.projectName}
`,
    },
  ];
}

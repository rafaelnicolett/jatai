import type { HarnessAdapter, GeneratedFile } from "./HarnessAdapter";
import type { WizardState } from "../../types";
import { orchestratorEntryBody } from "../../data/orchestrator-entry-prompt";
import { BRAND } from "../../data/brand.pure";
import { renameKitOrchestrator } from "./orchestrator";
import { entryPointParagraph } from "../content/entry-point";
import { MCP_CONFIG_FILES } from "../content/mcp-config";

/**
 * Gera .github/agents/, .github/skills/, .github/chatmodes/ e
 * .github/copilot-instructions.md para projetos com GitHub Copilot.
 */
export class CopilotAdapter implements HarnessAdapter {
  readonly name = "copilot";
  readonly hostDir = ".github";
  readonly instructionsFile = ".github/copilot-instructions.md";
  readonly kitInstructionsFile = "copilot-instructions.md";
  readonly supportsChatmodes = true;
  readonly slashCommandsDir = null;
  readonly projectHooksFile = null;
  readonly orchestratorFile = BRAND.files.orchestratorAgent;
  readonly genericAgentsMd = true;
  readonly mcpConfigs = MCP_CONFIG_FILES;
  readonly activity = "none";

  agentDestination(kitRel: string): string {
    return kitRel;
  }

  /**
   * Os agentes do kit já nascem com os paths do Copilot (`.github/agents/`).
   * Só o orquestrador muda de nome: `maestro.agent.md` → `<marca>.agent.md`,
   * o custom agent que é a entrada no seletor de agentes (ADR-0025).
   */
  adaptAgents(agentsDir: string): Promise<void> {
    return renameKitOrchestrator(agentsDir);
  }

  generateAgentArtifacts(
    _targetDir: string,
    state: WizardState
  ): Promise<GeneratedFile[]> {
    const files: GeneratedFile[] = [];
    const svcSnake = toSnake(state.projectName);

    // .github/copilot-instructions.md
    files.push({
      relativePath: ".github/copilot-instructions.md",
      content: copilotInstructions(state, svcSnake),
    });

    // .github/agents/ — placeholder agentes fase a fase
    for (const agent of getAgentStubs(state)) {
      files.push({
        relativePath: `.github/agents/${agent.filename}`,
        content: agent.content,
      });
    }

    // .github/chatmodes/maestro.chatmode.md
    files.push({
      relativePath: ".github/chatmodes/maestro.chatmode.md",
      content: maestroChatmode(state),
    });

    return Promise.resolve(files);
  }
}

// ── Generators ─────────────────────────────────────────────────────────────

/**
 * Como fazer no Copilot o que os agentes do kit pedem com ferramentas do
 * Claude Code (A18, F3.5). O mesmo texto está nas instruções brownfield do
 * Copilot (`kit/content/copilot-instructions.md`).
 */
export const COPILOT_HITL_SECTION = `## Perguntas ao humano no Copilot

Os agentes do kit foram escritos com as ferramentas do Claude Code. No Copilot:

- **\`AskUserQuestion\`** (pausa de validação humana): faça a pergunta no chat, com as opções numeradas, uma por linha. Em \`multiSelect\`, aceite vários números. **Pare e espere a resposta** antes de seguir; nunca responda pelo humano.
- **\`TodoWrite\`** (tracker de fases): mantenha a lista como \`- [ ]\` / \`- [x]\` no corpo da mensagem.
`;


function copilotInstructions(state: WizardState, svcSnake: string): string {
  return `---
applyTo: "**"
---
# Copilot Instructions — ${state.projectName}

> Generated by ${BRAND.displayName} · Template \`${BRAND.templatePrefix}${state.backendStack}\`

## Ponto de entrada único

${entryPointParagraph("copilot")}

## Stack
- Backend: **${state.backendStack}** · Service: \`${svcSnake}\`
${state.frontendStack !== "none" ? `- Frontend: **${state.frontendStack}**` : ""}
- Database: ${state.database ?? "postgresql"}
- Cloud: ${state.cloud ?? "none"}
- CI/CD: ${state.cicd ?? "github-actions"}

## Architecture
- Hexagonal / Ports & Adapters (domain → application → adapters)
- domain: zero framework import
- application: use cases + ports
- adapters: HTTP, DB, queue

## Conventions
- Errors: \`DomainError\` → 4xx + \`{ code, message, details, traceId }\`
- OTel: 1 span per adapter entry point
- Tests: unit (domain/ — no mocks), integration (Testcontainers)

${COPILOT_HITL_SECTION}`;
}

function maestroChatmode(state: WizardState): string {
  return `---
description: "Orquestrador — único ponto de entrada da ${BRAND.displayName} para ${state.projectName}"
---
# @maestro — Orquestrador de ${state.projectName}

${orchestratorEntryBody("copilot", state.projectName)}`;
}

interface AgentStub {
  filename: string;
  content: string;
}

function getAgentStubs(state: WizardState): AgentStub[] {
  return [
    {
      filename: "backend.agent.md",
      content: `---
id: backend-${state.backendStack}
stream: downstream
receives_from: [sprint-runner]
delivers_to: [reviewer]
---
# @backend-${state.backendStack}

Stack: **${state.backendStack}** · Project: ${state.projectName}
`,
    },
  ];
}

// ── Utils ──────────────────────────────────────────────────────────────────

function toSnake(s: string): string {
  return s.replace(/-/g, "_");
}
